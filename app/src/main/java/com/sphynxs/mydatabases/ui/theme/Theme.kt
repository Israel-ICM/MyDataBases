/**
 * Tema principal de la aplicación MyDataBases.
 *
 * Soporta tres modos de tema (LIGHT, DARK, SYSTEM) y dynamic color en Android 12+.
 * El dynamic color adapta los colores al wallpaper del usuario automáticamente.
 *
 * @param themeMode Modo de tema seleccionado por el usuario (default: SYSTEM)
 * @param dynamicColor Habilitar colores dinámicos en Android 12+ (default: true)
 * @param content Contenido de la app que se renderizará con este tema
 *
 * @author israel-icm
 * @date 2026-06-12
 */
@Composable
fun MyDataBasesTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit
) {
    val systemInDarkTheme = isSystemInDarkTheme()
    
    val darkTheme = when (themeMode) {
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
        ThemeMode.SYSTEM -> systemInDarkTheme
    }
    
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }
    
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            window.statusBarColor = colorScheme.primary.toArgb()
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}
